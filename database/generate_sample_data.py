#!/usr/bin/env python3
"""Generates database/sample_data.sql (demo users, investigators, 10 demo incidents).
Passwords are hashed with the same PBKDF2 format used by PasswordUtil.java."""
import base64, hashlib, datetime as dt

ITER = 120000
def h(pw, seed):
    salt = hashlib.sha256(seed.encode()).digest()[:16]            # fixed salt only for repeatable DEMO data
    dk = hashlib.pbkdf2_hmac('sha256', pw.encode(), salt, ITER, 32)
    return f"pbkdf2${ITER}${base64.b64encode(salt).decode()}${base64.b64encode(dk).decode()}"

users = [  # id, name, email, password, phone, role
 (1, "Demo Admin",                   "admin@cyberguard.demo",       "Admin@123",  "9000000001", "ADMIN"),
 (2, "Demo Investigator - Meera Nair","meera@cyberguard.demo",      "Invest@123", "9000000002", "INVESTIGATOR"),
 (3, "Demo Investigator - Rohan Das", "rohan@cyberguard.demo",      "Invest@123", "9000000003", "INVESTIGATOR"),
 (4, "Demo Investigator - Sana Khan", "sana@cyberguard.demo",       "Invest@123", "9000000004", "INVESTIGATOR"),
 (5, "Demo User - Aarav Sharma",     "aarav@demo.test",             "User@1234",  "9100000005", "CITIZEN"),
 (6, "Demo User - Priya Menon",      "priya@demo.test",             "User@1234",  "9100000006", "CITIZEN"),
 (7, "Demo User - Kabir Singh",      "kabir@demo.test",             "User@1234",  "9100000007", "CITIZEN"),
 (8, "Demo User - Isha Patel",       "isha@demo.test",              "User@1234",  "9100000008", "CITIZEN"),
 (9, "Demo User - Neil Fernandes",   "neil@demo.test",              "User@1234",  "9100000009", "CITIZEN"),
]
STEPS = ["SUBMITTED","UNDER_REVIEW","ASSIGNED","INVESTIGATION","RESOLVED","CLOSED"]
BASE = {"Phishing":40,"Fake Website":40,"Online Fraud":50,"Identity Theft":50,"Malware":55,
        "Account Compromise":60,"Unauthorized Access":60,"Cyberbullying":30,"Other":30}
FRAUDLIKE = {"Online Fraud","Identity Theft"}
def priority(t, loss):
    s = BASE[t] + (30 if loss >= 100000 else 15 if loss >= 10000 else 5 if loss > 0 else 0)
    p = "High" if s >= 75 else "Medium" if s >= 50 else "Low"
    return "High" if (t in FRAUDLIKE and loss >= 50000) else p

TEXT = {
 "Phishing": "Received an SMS claiming my bank account was blocked and clicked the link. The page asked for card details.",
 "Fake Website": "Ordered shoes from a website that looked genuine. The goods never arrived and the site has disappeared.",
 "Online Fraud": "A seller on a marketplace asked for an advance payment and stopped responding after the transfer.",
 "Identity Theft": "Found a loan application made in my name that I never submitted. Suspect my documents were leaked.",
 "Malware": "After installing a free video tool my files were renamed and a message demanded payment to unlock them.",
 "Account Compromise": "My email account password was changed and messages were sent to my contacts without my knowledge.",
 "Unauthorized Access": "Received alerts about logins to my cloud storage from an unknown country and files were deleted.",
 "Cyberbullying": "Anonymous accounts keep posting abusive comments and edited pictures of me on social media.",
}
# id, user, type, incident_date, loss, status, assigned_to
inc = [
 (1,5,"Phishing","2026-08-28",0,"CLOSED",2),
 (2,5,"Online Fraud","2026-09-02",45000,"RESOLVED",3),
 (3,6,"Account Compromise","2026-09-05",0,"INVESTIGATION",2),
 (4,6,"Malware","2026-09-08",0,"INVESTIGATION",4),
 (5,7,"Fake Website","2026-09-10",12000,"ASSIGNED",3),
 (6,7,"Cyberbullying","2026-09-15",0,"UNDER_REVIEW",None),
 (7,8,"Identity Theft","2026-09-18",150000,"UNDER_REVIEW",None),
 (8,8,"Unauthorized Access","2026-09-22",0,"SUBMITTED",None),
 (9,9,"Phishing","2026-09-27",2500,"SUBMITTED",None),
 (10,9,"Online Fraud","2026-09-12",8000,"RESOLVED",4),
]
uname = {u[0]: u for u in users}
q = lambda s: "'" + s.replace("'", "''") + "'"
out = ["-- DEMO / SAMPLE DATA - generated by generate_sample_data.py (do not use in production)",
       "USE cyberguard_db;", ""]
out.append("INSERT INTO users (user_id,name,email,password_hash,phone,role) VALUES")
out.append(",\n".join(f"({u[0]},{q(u[1])},{q(u[2])},{q(h(u[3], u[2]))},{q(u[4])},{q(u[5])})" for u in users) + ";\n")

inc_rows, hist_rows, note_rows = [], [], []
for (i, uid, t, d, loss, st, asg) in inc:
    k = STEPS.index(st)
    created = dt.datetime.fromisoformat(d) + dt.timedelta(days=1, hours=10)
    updated = created + dt.timedelta(days=k, hours=1)
    u = uname[uid]
    desc = "[DEMO DATA] " + TEXT[t]
    url = "http://secure-login-demo.example/verify" if t in ("Phishing","Fake Website") else None
    inc_rows.append("(%d,%s,%d,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,1,%s,%s)" % (
        i, q(f"CYB-2026-{i:05d}"), uid, q(u[1]), q(u[2]), q(u[4]), q(t), q(desc), q(d),
        q(url) if url else "NULL", loss, "NULL", q(priority(t, loss)), q(st),
        asg if asg else "NULL", q(str(created)), q(str(updated))))
    for s in range(k + 1):
        by = "NULL" if s == 0 else (1 if s <= 2 or not asg else asg)
        old = "NULL" if s == 0 else q(STEPS[s-1])
        hist_rows.append("(%d,%s,%s,%s,%s)" % (i, old, q(STEPS[s]), by, q(str(created + dt.timedelta(days=s)))))
    if asg:
        who = uname[asg][1].split(" - ")[-1]
        note_rows.append("(%d,%d,%s,1,%s)" % (i, asg, q(f"Your case has been assigned to {who}. We will contact you if more information is needed."), q(str(created + dt.timedelta(days=2)))))
        if k >= 3:
            note_rows.append("(%d,%d,%s,1,%s)" % (i, asg, q("Initial evidence review completed. The investigation is in progress."), q(str(created + dt.timedelta(days=3)))))
            note_rows.append("(%d,%d,%s,0,%s)" % (i, asg, q("INTERNAL: cross-checked indicators with previous demo cases; no link found yet."), q(str(created + dt.timedelta(days=3, hours=2)))))
        if k >= 4:
            note_rows.append("(%d,%d,%s,1,%s)" % (i, asg, q("Case resolved. Please follow the safety advice shown on your case page."), q(str(created + dt.timedelta(days=4)))))

out.append("INSERT INTO incidents (incident_id,case_id,user_id,reporter_name,reporter_email,reporter_phone,incident_type,description,incident_date,suspicious_url,financial_loss,additional_info,priority,status,assigned_to,is_demo,created_at,updated_at) VALUES")
out.append(",\n".join(inc_rows) + ";\n")
out.append("INSERT INTO case_status_history (incident_id,old_status,new_status,updated_by,updated_at) VALUES")
out.append(",\n".join(hist_rows) + ";\n")
out.append("INSERT INTO investigations (incident_id,investigator_id,notes,is_public,created_at) VALUES")
out.append(",\n".join(note_rows) + ";\n")
open("database/sample_data.sql", "w").write("\n".join(out))
print("wrote database/sample_data.sql:", len(users), "users,", len(inc), "incidents")
